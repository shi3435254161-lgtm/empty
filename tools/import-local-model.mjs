import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { execFile } from "node:child_process";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);
const rootDir = path.resolve(import.meta.dirname, "..");
const incomingDir = path.join(rootDir, "assets", "models", "incoming");
const wwwIncomingDir = path.join(rootDir, "www", "assets", "models", "incoming");
const registryPath = path.join(incomingDir, "registry.json");
const generatedPaths = [
  path.join(rootDir, "js", "incoming-assets.generated.js"),
  path.join(rootDir, "www", "js", "incoming-assets.generated.js")
];

function usage(message = "") {
  if (message) console.error(message);
  console.error("Usage: node tools/import-local-model.mjs <model.glb|model.gltf|archive.zip> --id <asset-id> --name <display-name> --source <url> --license <license> [--module <module-id>] [--model <archive-relative-path>]");
  process.exit(1);
}

function parseArguments(argv) {
  const [source, ...rest] = argv;
  const options = { module: "asset-audit-only" };
  for (let index = 0; index < rest.length; index += 2) {
    const flag = rest[index];
    const value = rest[index + 1];
    if (!flag?.startsWith("--") || value == null) usage(`Invalid argument: ${flag || ""}`);
    options[flag.slice(2)] = value;
  }
  return { source, options };
}

async function fileExists(filePath) {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function copyTree(source, target) {
  await fs.mkdir(target, { recursive: true });
  const entries = await fs.readdir(source, { withFileTypes: true });
  await Promise.all(entries.map(async entry => {
    const from = path.join(source, entry.name);
    const to = path.join(target, entry.name);
    if (entry.isDirectory()) await copyTree(from, to);
    else await fs.copyFile(from, to);
  }));
}

async function copyModelBundle(modelFile, target) {
  await fs.mkdir(target, { recursive: true });
  const extension = path.extname(modelFile).toLowerCase();
  const targetModel = path.join(target, path.basename(modelFile));
  await fs.copyFile(modelFile, targetModel);
  if (extension === ".glb") return path.basename(modelFile);

  const sourceFolder = path.dirname(modelFile);
  const gltf = JSON.parse(await fs.readFile(modelFile, "utf8"));
  const uris = [
    ...(gltf.buffers || []).map(item => item.uri),
    ...(gltf.images || []).map(item => item.uri)
  ].filter(uri => typeof uri === "string" && !uri.startsWith("data:"));

  for (const uri of new Set(uris)) {
    const sourceDependency = path.resolve(sourceFolder, uri);
    const relativeDependency = path.relative(sourceFolder, sourceDependency);
    if (relativeDependency.startsWith("..") || path.isAbsolute(relativeDependency)) {
      throw new Error(`glTF dependency escapes its model folder: ${uri}`);
    }
    await fs.mkdir(path.dirname(path.join(target, relativeDependency)), { recursive: true });
    await fs.copyFile(sourceDependency, path.join(target, relativeDependency));
  }
  return path.basename(modelFile);
}

async function findModelFiles(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const matches = [];
  for (const entry of entries) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) matches.push(...await findModelFiles(entryPath));
    else if (/\.(glb|gltf)$/i.test(entry.name)) matches.push(entryPath);
  }
  return matches;
}

async function directorySize(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const sizes = await Promise.all(entries.map(async entry => {
    const itemPath = path.join(directory, entry.name);
    return entry.isDirectory() ? directorySize(itemPath) : (await fs.stat(itemPath)).size;
  }));
  return sizes.reduce((total, bytes) => total + bytes, 0);
}

async function loadRegistry() {
  if (!await fileExists(registryPath)) return [];
  const parsed = JSON.parse(await fs.readFile(registryPath, "utf8"));
  return Array.isArray(parsed) ? parsed : [];
}

async function writeRegistry(records) {
  await fs.mkdir(incomingDir, { recursive: true });
  await fs.writeFile(registryPath, `${JSON.stringify(records, null, 2)}\n`, "utf8");
  const grouped = records.reduce((result, asset) => {
    const moduleId = asset.moduleId || "asset-audit-only";
    if (!result[moduleId]) result[moduleId] = [];
    result[moduleId].push({
      id: asset.id,
      name: asset.name,
      ready: true,
      sourceUrl: asset.sourceUrl,
      author: asset.author || "待核验",
      license: asset.license,
      url: asset.url,
      format: asset.format,
      bytes: asset.bytes,
      auditOnly: true,
      note: "本地下载文件，待授权和空间验收。"
    });
    return result;
  }, {});
  const source = [
    "// Generated by tools/import-local-model.mjs. Do not hand edit.",
    "window.INCOMING_REAL_ASSETS = " + JSON.stringify(grouped, null, 2) + ";",
    ""
  ].join("\n");
  await Promise.all(generatedPaths.map(filePath => fs.writeFile(filePath, source, "utf8")));
}

const { source, options } = parseArguments(process.argv.slice(2));
if (!source || !options.id || !options.name || !options.source || !options.license) usage("Model metadata is required.");
if (!/^[a-z0-9][a-z0-9-]{2,80}$/.test(options.id)) usage("Asset id must use lowercase letters, numbers, and hyphens.");

const sourcePath = path.resolve(process.cwd(), source);
if (!await fileExists(sourcePath)) usage(`File not found: ${sourcePath}`);
const extension = path.extname(sourcePath).toLowerCase();
if (![".glb", ".gltf", ".zip"].includes(extension)) usage("Only .glb, .gltf, and .zip files are supported.");

const targetDir = path.join(incomingDir, options.id);
const targetWwwDir = path.join(wwwIncomingDir, options.id);
await fs.rm(targetDir, { recursive: true, force: true });
await fs.rm(targetWwwDir, { recursive: true, force: true });

let modelPath;
let copiedModelPath;
let temporaryDir;
try {
  if (extension === ".zip") {
    temporaryDir = await fs.mkdtemp(path.join(os.tmpdir(), "kitchen-designer-model-"));
    await execFileAsync("tar.exe", ["-xf", sourcePath, "-C", temporaryDir]);
    const choices = await findModelFiles(temporaryDir);
    const requested = options.model && path.resolve(temporaryDir, options.model);
    modelPath = requested || (choices.length === 1 ? choices[0] : null);
    if (!modelPath || !choices.includes(modelPath)) {
      const relativeChoices = choices.map(filePath => path.relative(temporaryDir, filePath)).join(", ");
      throw new Error(`Archive contains ${choices.length} model files. Re-run with --model <one of: ${relativeChoices}>`);
    }
    copiedModelPath = await copyModelBundle(modelPath, targetDir);
  } else {
    copiedModelPath = await copyModelBundle(sourcePath, targetDir);
  }

  await copyTree(targetDir, targetWwwDir);
  const records = (await loadRegistry()).filter(record => record.id !== options.id);
  const bytes = await directorySize(targetDir);
  records.push({
    id: options.id,
    moduleId: options.module,
    name: options.name,
    sourceUrl: options.source,
    author: options.author || "待核验",
    license: options.license,
    url: `assets/models/incoming/${options.id}/${copiedModelPath}`,
    format: path.extname(copiedModelPath).slice(1).toLowerCase(),
    bytes
  });
  records.sort((a, b) => a.name.localeCompare(b.name, "zh-CN"));
  await writeRegistry(records);
  console.log(`Imported ${options.name} (${(bytes / 1024 / 1024).toFixed(2)} MB) as audit-only asset ${options.id}.`);
} finally {
  if (temporaryDir) await fs.rm(temporaryDir, { recursive: true, force: true });
}
